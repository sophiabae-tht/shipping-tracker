// Generates src/styles/tokens.css (a Tailwind v4 @theme) from two sources:
//   design-tokens/figma-variables.json   Figma variables, text styles and effect styles (wins on conflicts)
//   design-tokens/live-enroll-tokens.json tokens from enroll.thrivemobile.com's production CSS, adding the
//                                         primitive palette, extra semantic colors, weights and radii
// Figma names map 1:1 to classes: text/strong -> text-text-strong, fill/brandStrong -> bg-fill-brand-strong,
// spacing/16 -> p-16, cornerRadius/16 -> rounded-16, "Small/Bold" -> type-small-bold, raised -> shadow-raised.
import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => JSON.parse(readFileSync(new URL(`../design-tokens/${file}`, import.meta.url), "utf8"));
const src = read("figma-variables.json");
const live = read("live-enroll-tokens.json");

const kebab = (name) =>
  name
    .split("/")
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/\s+/g, "-").toLowerCase())
    .join("-");

const WEB_FONT = "General Sans Web";
const colorVar = (figmaName) => `var(--color-${kebab(figmaName)})`;
const typo = src.typography;
const lines = [];
const push = (s = "") => lines.push(s);

push("/* GENERATED by scripts/build-tokens.mjs from design-tokens/*.json. Do not edit by hand. */");
push();
// Same font file as enroll.thrivemobile.com: the variable General Sans, so fontWeight/strong (620) renders a
// true 620 like production. Registered under a distinct family name with an explicit weight range so a locally
// installed copy of General Sans can't take over (Chrome would snap 620 to that copy's Bold instance).
push("@font-face {");
push(`  font-family: "${WEB_FONT}";`);
push(`  src: url("${live.font.file}") format("${live.font.format}");`);
push(`  font-weight: ${live.font.weightRange};`);
push("  font-style: normal;");
push("  font-display: swap;");
push("}");
push();
push("@theme {");
push("  /* Only design tokens are available: Tailwind's default palette, spacing, radii and shadows are cleared. */");
push("  --color-*: initial;");
push("  --spacing-*: initial;");
push("  --radius-*: initial;");
push("  --shadow-*: initial;");
push("  --font-*: initial;");
push("  --font-weight-*: initial;");
push("  --text-*: initial;");
push();
push("  /* colorsSemantic */");
for (const [name, value] of Object.entries(src.colorsSemantic)) push(`  --color-${kebab(name)}: ${value};`);
push("  --color-transparent: transparent;");
push();
push("  /* colorsSemantic added from the live enrollment site (not defined in Figma) */");
const figmaColors = new Set(Object.keys(src.colorsSemantic).map(kebab));
for (const [name, ref] of Object.entries(live.colorsSemantic)) {
  if (figmaColors.has(kebab(name))) continue;
  push(`  --color-${kebab(name)}: ${ref.startsWith("#") ? ref : `var(--color-${ref})`};`);
}
push();
push("  /* primitive palette (live enrollment site); semantic tokens above are what components use */");
for (const [name, value] of Object.entries(live.primitives)) push(`  --color-${name}: ${value};`);
push();
push("  /* spacing */");
for (const [name, value] of Object.entries(src.spacing)) {
  if (name.startsWith("spacing/")) push(`  --spacing-${name.slice("spacing/".length)}: ${value}px;`);
}
for (const [key, value] of Object.entries(live.spacing)) push(`  --spacing-${key}: ${value}; /* live */`);
push();
push("  /* corner radius (cornerRadius/* plus spacing/* where Figma binds spacing to radius) */");
for (const [name, value] of Object.entries(src.spacing)) {
  const key = name.split("/")[1];
  if (name.startsWith("cornerRadius/") || ["4", "12"].includes(key)) push(`  --radius-${key}: ${value}px;`);
}
const figmaRadii = new Set(["4", "12", "16"]);
for (const [key, value] of Object.entries(live.radius)) if (!figmaRadii.has(key)) push(`  --radius-${key}: ${value}; /* live */`);
push();
push("  /* typography */");
const families = new Set();
for (const [name, value] of Object.entries(typo)) {
  if (name.startsWith("fontFamily/")) {
    const family = value === "General Sans Variable" ? WEB_FONT : value;
    push(`  --font-${kebab(name.slice("fontFamily/".length))}: "${family}", "Plus Jakarta Sans", ui-sans-serif, system-ui, sans-serif; /* ${name}: ${value} */`);
    families.add(name);
  }
}
const figmaWeights = new Set();
for (const [name, value] of Object.entries(typo)) {
  if (!name.startsWith("fontWeight/")) continue;
  const key = kebab(name.slice("fontWeight/".length));
  if (live.fontWeight[key] !== undefined && live.fontWeight[key] !== value) {
    throw new Error(`fontWeight/${key}: Figma ${value} vs live ${live.fontWeight[key]}`);
  }
  figmaWeights.add(key);
  push(`  --font-weight-${key}: ${value};`);
}
// Live-only weight names (light, medium, semibold, bold) so production class names work here too.
for (const [key, value] of Object.entries(live.fontWeight)) if (!figmaWeights.has(key)) push(`  --font-weight-${key}: ${value}; /* live */`);
for (const [name, value] of Object.entries(typo)) {
  if (!name.startsWith("fontSize/")) continue;
  const key = kebab(name.slice("fontSize/".length));
  push(`  --text-${key}: ${value}px;`);
  const lh = typo[`lineHeight/${name.slice("fontSize/".length)}`];
  if (lh) push(`  --text-${key}--line-height: ${lh}px;`);
}
push();
push("  /* effect styles */");
for (const [name, layers] of Object.entries(src.effectStyles)) {
  const value = layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${colorVar(l.color)}`).join(", ");
  push(`  --shadow-${kebab(name)}: ${value};`);
}
push("}");
push();
push("/* text styles */");
for (const [name, style] of Object.entries(src.textStyles)) {
  const util = `type-${kebab(name.replace(/\s+(\d)/g, "$1"))}`;
  const key = (ref) => kebab(ref.split("/")[1]);
  push(`@utility ${util} {`);
  push(`  font-family: var(--font-${key(style.family)});`);
  push(`  font-size: var(--text-${key(style.size)});`);
  push(`  line-height: var(--text-${key(style.size)}--line-height);`);
  push(`  font-weight: var(--font-weight-${key(style.weight)});`);
  push(`  letter-spacing: ${style.letterSpacing}px;`);
  if (style.textTransform) push(`  text-transform: ${style.textTransform};`);
  push("}");
}

writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), lines.join("\n") + "\n");
console.log("Wrote src/styles/tokens.css");
