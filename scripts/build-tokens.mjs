// Generates src/styles/tokens.css (a Tailwind v4 @theme) from the Figma variables export.
// Figma names map 1:1 to classes: text/strong -> text-text-strong, fill/brandStrong -> bg-fill-brand-strong,
// spacing/16 -> p-16, cornerRadius/16 -> rounded-16, "Small/Bold" -> type-small-bold, raised -> shadow-raised.
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("../design-tokens/figma-variables.json", import.meta.url), "utf8"));

const kebab = (name) =>
  name
    .split("/")
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/\s+/g, "-").toLowerCase())
    .join("-");

const WEB_FONT = "General Sans Web";
const colorVar = (figmaName) => `var(--color-${kebab(figmaName)})`;
const typo = src.typography;
const lines = [];
const push = (s = "") => lines.push(s);

push("/* GENERATED by scripts/build-tokens.mjs from design-tokens/figma-variables.json. Do not edit by hand. */");
push();
// Figma's fontFamily is "General Sans Variable"; the designs use the Medium and Semibold cuts, supplied as
// public/figma/fonts/*.otf. They're registered under a distinct family name so a locally installed copy of
// General Sans can't take over (Chrome would snap weight 620 to its Bold instance).
// Semibold covers 600-700, so fontWeight/mid (600) and fontWeight/strong (620) both render it, never faux bold.
const FACES = [
  { file: "GeneralSans-Medium.otf", weight: "500" },
  { file: "GeneralSans-Semibold.otf", weight: "600 700" },
];
for (const face of FACES) {
  push("@font-face {");
  push(`  font-family: "${WEB_FONT}";`);
  push(`  src: url("/figma/fonts/${face.file}") format("opentype");`);
  push(`  font-weight: ${face.weight};`);
  push("  font-style: normal;");
  push("  font-display: swap;");
  push("}");
}
push();
push("@theme {");
push("  /* Only Figma tokens are available: Tailwind's default palette, spacing, radii and shadows are cleared. */");
push("  --color-*: initial;");
push("  --spacing-*: initial;");
push("  --radius-*: initial;");
push("  --shadow-*: initial;");
push("  --font-*: initial;");
push("  --font-weight-*: initial;");
push("  --text-*: initial;");
push();
push("  /* colorsSemantic */");
for (const [name, value] of Object.entries(src.colorsSemantic)) push(`  --color-${kebab(name)}: ${value};`);
push("  --color-transparent: transparent;");
push();
push("  /* spacing */");
for (const [name, value] of Object.entries(src.spacing)) {
  if (name.startsWith("spacing/")) push(`  --spacing-${name.slice("spacing/".length)}: ${value}px;`);
}
push();
push("  /* corner radius (cornerRadius/* plus spacing/* where Figma binds spacing to radius) */");
for (const [name, value] of Object.entries(src.spacing)) {
  const key = name.split("/")[1];
  if (name.startsWith("cornerRadius/") || ["4", "12"].includes(key)) push(`  --radius-${key}: ${value}px;`);
}
push();
push("  /* typography */");
const families = new Set();
for (const [name, value] of Object.entries(typo)) {
  if (name.startsWith("fontFamily/")) {
    const family = value === "General Sans Variable" ? WEB_FONT : value;
    push(`  --font-${kebab(name.slice("fontFamily/".length))}: "${family}", "Plus Jakarta Sans", ui-sans-serif, system-ui, sans-serif; /* ${name}: ${value} */`);
    families.add(name);
  }
}
for (const [name, value] of Object.entries(typo)) {
  if (name.startsWith("fontWeight/")) push(`  --font-weight-${kebab(name.slice("fontWeight/".length))}: ${value};`);
}
for (const [name, value] of Object.entries(typo)) {
  if (!name.startsWith("fontSize/")) continue;
  const key = kebab(name.slice("fontSize/".length));
  push(`  --text-${key}: ${value}px;`);
  const lh = typo[`lineHeight/${name.slice("fontSize/".length)}`];
  if (lh) push(`  --text-${key}--line-height: ${lh}px;`);
}
push();
push("  /* effect styles */");
for (const [name, layers] of Object.entries(src.effectStyles)) {
  const value = layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${colorVar(l.color)}`).join(", ");
  push(`  --shadow-${kebab(name)}: ${value};`);
}
push("}");
push();
push("/* text styles */");
for (const [name, style] of Object.entries(src.textStyles)) {
  const util = `type-${kebab(name.replace(/\s+(\d)/g, "$1"))}`;
  const key = (ref) => kebab(ref.split("/")[1]);
  push(`@utility ${util} {`);
  push(`  font-family: var(--font-${key(style.family)});`);
  push(`  font-size: var(--text-${key(style.size)});`);
  push(`  line-height: var(--text-${key(style.size)}--line-height);`);
  push(`  font-weight: var(--font-weight-${key(style.weight)});`);
  push(`  letter-spacing: ${style.letterSpacing}px;`);
  if (style.textTransform) push(`  text-transform: ${style.textTransform};`);
  push("}");
}

writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), lines.join("\n") + "\n");
console.log("Wrote src/styles/tokens.css");
